begin;
create table if not exists venue (
  id bigint generated by default as identity primary key,
  venue_name varchar(120) not null,
  address varchar(255) not null
);
create table if not exists event (
  id bigint generated by default as identity primary key,
  venue_id bigint not null references venue(id),
  event_name varchar(120) not null,
  start_date date not null,
  end_date date not null,
  constraint event_dates_valid check (start_date <= end_date)
);
create table if not exists booth (
  id bigint generated by default as identity primary key,
  event_id bigint not null references event(id),
  booth_code varchar(30) not null,
  location_note varchar(200) not null,
  unique(event_id, booth_code)
);
create table if not exists shift (
  id bigint generated by default as identity primary key,
  booth_id bigint not null references booth(id),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  constraint shift_times_valid check (starts_at < ends_at)
);
create table if not exists staff (
  id bigint generated by default as identity primary key,
  login_name varchar(60) not null unique,
  full_name varchar(80) not null,
  staff_role varchar(30) not null check (staff_role in ('sales_consultant','manager')),
  is_active boolean not null default true
);
create table if not exists shift_assignment (
  id bigint generated by default as identity primary key,
  shift_id bigint not null references shift(id),
  staff_id bigint not null references staff(id),
  assignment_status varchar(20) not null check (assignment_status in ('assigned','cancelled')),
  unique(shift_id, staff_id)
);
create table if not exists product_category (
  id bigint generated by default as identity primary key,
  category_name varchar(80) not null unique
);
create table if not exists product (
  id bigint generated by default as identity primary key,
  category_id bigint not null references product_category(id),
  sku varchar(40) not null unique,
  product_name varchar(120) not null,
  min_unit_price numeric(12,2) not null check (min_unit_price >= 0),
  is_active boolean not null default true
);
create table if not exists sale (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references shift_assignment(id),
  sold_at timestamptz not null default now(),
  total_amount numeric(14,2) not null check (total_amount >= 0)
);
create table if not exists sale_line (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references sale(id) on delete cascade,
  product_id bigint not null references product(id),
  line_no integer not null check (line_no > 0),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_amount numeric(14,2) not null check (line_amount >= 0),
  unique(sale_id, line_no)
);

create index if not exists sale_sold_at_idx on sale(sold_at);
create index if not exists sale_assignment_idx on sale(assignment_id);
create index if not exists sale_line_product_idx on sale_line(product_id);

alter table venue enable row level security;
alter table event enable row level security;
alter table booth enable row level security;
alter table shift enable row level security;
alter table staff enable row level security;
alter table shift_assignment enable row level security;
alter table product_category enable row level security;
alter table product enable row level security;
alter table sale enable row level security;
alter table sale_line enable row level security;

create or replace function register_sale(p_assignment_id bigint, p_lines jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_sale_id bigint; v_total numeric(14,2); v_line jsonb; v_product product%rowtype;
  v_quantity integer; v_price numeric(12,2); v_line_no integer := 0;
begin
  if jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then raise exception '销售明细不能为空'; end if;
  if not exists (
    select 1 from shift_assignment sa join shift s on s.id=sa.shift_id
    where sa.id=p_assignment_id and sa.assignment_status='assigned' and now() between s.starts_at and s.ends_at
  ) then raise exception '当前班次无效，无法录入销售'; end if;
  v_total := 0;
  for v_line in select * from jsonb_array_elements(p_lines) loop
    v_quantity := (v_line->>'quantity')::integer; v_price := (v_line->>'unit_price')::numeric;
    select * into v_product from product where id=(v_line->>'product_id')::bigint and is_active;
    if not found then raise exception '商品无效'; end if;
    if v_quantity <= 0 then raise exception '销售数量必须为正整数'; end if;
    if v_price < v_product.min_unit_price then raise exception '成交单价不得低于最低售价：%', v_product.min_unit_price; end if;
    v_total := v_total + round(v_quantity * v_price, 2);
  end loop;
  insert into sale(assignment_id,total_amount) values(p_assignment_id,v_total) returning id into v_sale_id;
  for v_line in select * from jsonb_array_elements(p_lines) loop
    v_line_no := v_line_no + 1; v_quantity := (v_line->>'quantity')::integer; v_price := (v_line->>'unit_price')::numeric;
    insert into sale_line(sale_id,product_id,line_no,quantity,unit_price,line_amount)
    values(v_sale_id,(v_line->>'product_id')::bigint,v_line_no,v_quantity,v_price,round(v_quantity*v_price,2));
  end loop;
  return v_sale_id;
end $$;

